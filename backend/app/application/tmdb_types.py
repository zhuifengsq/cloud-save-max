"""Typed ports used by the TMDB cache use cases."""
from __future__ import annotations

from datetime import date, datetime
from typing import Any, Callable, Protocol
from sqlalchemy.orm import Session
from app.domain.tmdb import MediaType


from app.domain.tmdb_cache import CacheRow as CacheRow, CacheSetting as CacheSetting, WriterOptions as WriterOptions


class TMDBClientPort(Protocol):
    def get_movie_details(self, movie_id: int, *, language: str | None = None) -> dict[str, Any] | None: ...
    def get_tv_details(self, tv_id: int, *, language: str | None = None) -> dict[str, Any] | None: ...
    def get_tv_season(self, tv_id: int, season_number: int, *, language: str | None = None) -> dict[str, Any] | None: ...
    def get_tv_episode(self, tv_id: int, season_number: int, episode_number: int, *, language: str | None = None) -> dict[str, Any] | None: ...
    def get_movie_credits(self, movie_id: int) -> dict[str, Any] | None: ...
    def get_tv_credits(self, tv_id: int) -> dict[str, Any] | None: ...


class TMDBCacheStorePort(Protocol):
    def read(self, db: Session, key: dict[str, Any], *, reload: bool = False) -> CacheRow | None: ...
    def get_setting(self, db: Session, setting_id: int) -> CacheSetting | None: ...
    def touch(self, db: Session, row: CacheRow, accessed_at: datetime, options: WriterOptions = WriterOptions()) -> None: ...
    def claim(self, db: Session, key: dict[str, Any], now: datetime, *, credits: bool, force: bool = False, existing_only: bool = False, options: WriterOptions = WriterOptions()) -> bool: ...
    def complete(self, db: Session, key: dict[str, Any], started_at: datetime, values: dict[str, Any], *, credits: bool, options: WriterOptions = WriterOptions()) -> bool: ...
    def linked_targets(self, db: Session, *, enabled_only: bool) -> list[tuple[str, int]]: ...
    def expired_targets(self, db: Session, *, language: str, poster_language: str, now: datetime, max_items: int) -> list[tuple[str, int]]: ...
    def purge(self, db: Session, *, retention_days: int = 60, now: datetime) -> int: ...
    def list_rows(self, db: Session, *, language: str, poster_language: str, now: datetime, page: int = 1, page_size: int = 20, media_type: str | None = None, q: str | None = None, status: str | None = None, expired_only: bool = False) -> tuple[int, list[CacheRow]]: ...
    def set_ttl(self, db: Session, key: dict[str, Any], expires_at: datetime) -> CacheRow | None: ...
    def delete(self, db: Session, key: dict[str, Any]) -> int: ...


class TMDBDetailFetcherPort(Protocol):
    def fetch(self, client: TMDBClientPort, *, media_type: MediaType, tmdb_id: int, language: str, poster_language: str) -> tuple[dict[str, Any] | None, list[int], list[int]]: ...
    def correct_episode_dates(self, season: Any, client: TMDBClientPort, tmdb_id: int, season_number: int, *, budget: int = 20, stop_after_no_change: int = 6, today: date | None = None) -> int: ...
    def infer_update_weekdays(self, tv_id: int, details: dict[str, Any], client: TMDBClientPort) -> list[int]: ...


class TMDBRefreshBackgroundPort(Protocol):
    def submit(self, db: Session, job: tuple[str, int, str, str], refresh: Callable[[Session], None]) -> bool: ...
