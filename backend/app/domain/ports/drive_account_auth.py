"""Provider and account boundaries for interactive drive authentication."""
from typing import Any, Protocol
from app.domain.ports.drive_account import DriveAccountRecord

Config = dict[str, Any]

class QrcodeAuthProvider(Protocol):
    def generate_qrcode(self) -> Config: ...
    def query_qrcode_status(self, t: str, ck: str) -> Config: ...

class ChallengeAdapter(Protocol):
    def submit_captcha(self, code: str) -> object: ...
    def send_sms(self) -> object: ...
    def submit_sms(self, code: str) -> object: ...
    def export_runtime_config(self) -> Config: ...

class AccountAuthGateway(Protocol):
    def prepare(self, db: Any, account_id: int, expected_version: int | None = None) -> int: ...
    def get(self, db: Any, account_id: int) -> DriveAccountRecord: ...
    def probe(self, db: Any, account_id: int, *, config: Config | None = None,
              auth_completed: bool = False, expected_version: int | None = None) -> DriveAccountRecord: ...
