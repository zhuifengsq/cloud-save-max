"""Uniform lead-in capability and provider ports."""

from typing import Any, Protocol


class LeadInPort(Protocol):
    def ensure_initialized(self, *, ttl_seconds: int) -> Any: ...
    def lead_in_resolve_material(self, *args) -> dict: ...
    def lead_in_resolve_dir(self, *args) -> dict: ...
    def lead_in_inspect(self, *args) -> dict: ...
    def lead_in_add(self, *args) -> dict: ...
    def lead_in_verify(self, *args) -> dict: ...
    def lead_in_resolve_own_file(self, *args) -> dict: ...
    def lead_in_list_own_dir(self, *args) -> dict: ...
    def lead_in_copy_own_file(self, *args) -> dict: ...


class LeadInProviderPort(Protocol):
    def create(self, account: Any) -> LeadInPort | None: ...
